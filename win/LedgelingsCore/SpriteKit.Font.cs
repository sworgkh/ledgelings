    /// <summary>Width in font pixels of <paramref name="text"/>: 5 per letter and 1 between letters.</summary>
    public static int TextWidth(string text) => text.Length == 0 ? 0 : text.Length * 6 - 1;

    /// <summary>Draw <paramref name="text"/> with its top-left at (x, y), each font pixel <paramref name="size"/> image pixels.</summary>
    public static void Draw(string text, int x, int y, int size, SpriteText.Tint colour, SpriteText.Image image)
    {
        var upper = text.ToUpperInvariant();
        for (var i = 0; i < upper.Length; i++)
        {
            var rows = Glyphs.TryGetValue(upper[i], out var g) ? g : Glyphs[' '];
            for (var gy = 0; gy < rows.Length; gy++)
                for (var gx = 0; gx < rows[gy].Length; gx++)
                    if (rows[gy][gx] == '#') Fill(image, x + (i * 6 + gx) * size, y + gy * size, size, size, colour);
        }
    }
