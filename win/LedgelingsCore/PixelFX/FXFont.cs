// pixelfx's two pixel fonts (https://github.com/patch-gg/pixelfx, MIT): "mini" (3×5) for small numbers
// and tags, "big" (5×7) for words. Glyphs are trimmed to their inked columns, so text sets proportionally.

namespace Ledgelings.Core.PixelFX;

public sealed class FXFont
{
    public enum Align { Left, Center, Right }
    public readonly int H, Space, Gap;
    readonly Dictionary<char, (int W, bool[][] Rows)> glyphs = new();

    FXFont(int h, int space, int gap, Dictionary<char, string> table)
    {
        H = h; Space = space; Gap = gap;
        foreach (var (ch, src) in table)
        {
            var rows = src.Split('|').Select(r => r.Select(p => p == '#').ToArray()).ToArray();
            glyphs[ch] = (rows[0].Length, rows);
        }
    }

    (int W, bool[][] Rows)? Glyph(char ch) =>
        glyphs.TryGetValue(ch, out var g) ? g : glyphs.TryGetValue(char.ToUpperInvariant(ch), out var u) ? u : null;

    /// <summary>Width in font pixels of a string, before scaling.</summary>
    public int Width(string str)
    {
        int w = 0;
        foreach (var ch in str) w += (Glyph(ch)?.W ?? Space) + Gap;
        return Math.Max(0, w - Gap);
    }

    /// <summary>plot(x, y) for every inked pixel of str, the text's top-left at (0, 0).</summary>
    public void Raster(string str, Action<double, double> plot)
    {
        int x = 0;
        foreach (var ch in str)
        {
            if (Glyph(ch) is not { } g) { x += Space + Gap; continue; }
            for (int r = 0; r < H; r++) for (int c = 0; c < g.W; c++) if (g.Rows[r][c]) plot(x + c, r);
            x += g.W + Gap;
        }
    }

