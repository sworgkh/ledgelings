    /// Width in font pixels of `text`: 5 per letter and 1 between letters.
    static func textWidth(_ text: String) -> Int { text.isEmpty ? 0 : text.count * 6 - 1 }

    /// Draw `text` with its top-left at (`x`, `y`), each font pixel `size` image pixels.
    public static func draw(_ text: String, x: Int, y: Int, size: Int, colour: SpriteText.Tint, on image: inout SpriteText.Image) {
        for (i, letter) in text.uppercased().enumerated() {
            let rows = glyphs[letter] ?? glyphs[" "]!
            for (gy, row) in rows.enumerated() {
                for (gx, dot) in row.enumerated() where dot == "#" {
                    fill(&image, x: x + (i * 6 + gx) * size, y: y + gy * size, w: size, h: size, colour)
                }
            }
        }
    }
