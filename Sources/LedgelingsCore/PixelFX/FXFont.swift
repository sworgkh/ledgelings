// pixelfx's two pixel fonts (https://github.com/patch-gg/pixelfx, MIT): "mini" (3×5) for small numbers
// and tags, "big" (5×7) for words. Glyphs are trimmed to their inked columns, so text sets proportionally.

public struct FXFont: Sendable {
    public enum Align: Sendable { case left, center, right }
    public let h: Int, space: Int, gap: Int
    let glyphs: [Swift.Character: (w: Int, rows: [[Bool]])]

    init(h: Int, space: Int, gap: Int, table: [String: String]) {
        self.h = h; self.space = space; self.gap = gap
        var g: [Swift.Character: (w: Int, rows: [[Bool]])] = [:]
        for (ch, src) in table {
            let rows = src.split(separator: "|").map { $0.map { $0 == "#" } }
            g[Swift.Character(ch)] = (rows[0].count, rows)
        }
        glyphs = g
    }

    func glyph(_ ch: Swift.Character) -> (w: Int, rows: [[Bool]])? { glyphs[ch] ?? glyphs[Swift.Character(ch.uppercased())] }

    /// Width in font pixels of a string, before scaling.
    public func width(of str: String) -> Int {
        var w = 0
        for ch in str { w += (glyph(ch)?.w ?? space) + gap }
        return Swift.max(0, w - gap)
    }

    /// plot(x, y) for every inked pixel of str, the text's top-left at (0, 0).
    public func raster(_ str: String, _ plot: (Double, Double) -> Void) {
        var x = 0
        for ch in str {
            guard let g = glyph(ch) else { x += space + gap; continue }
            for r in 0..<h { for c in 0..<g.w where g.rows[r][c] { plot(Double(x + c), Double(r)) } }
            x += g.w + gap
        }
    }

