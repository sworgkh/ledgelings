extension SpriteText {
    /// `prompt(example:)` in Russian. The keys (`name:`, `kind:`, `colour:`, `character:`,
    /// `pose:`), the pose names and the letters stay exactly as the parser reads them.
    public static func russianPrompt(example: [String]) -> String {
        """
        Мне нужно крошечное пиксельное существо для настольной игрушки, записанное текстом, чтобы его можно было вставить обратно.
        Существо: \(describePlaceholder)

        Запиши его как лист спрайтов строго в этом текстовом формате и больше ничего не пиши:

        name: <одно слово строчными латинскими буквами, только буквы и цифры>
        kind: <что это такое, в нескольких словах, например «толстая зелёная лягушка с большими глазами»>
        colour: <цвет тела шестью шестнадцатеричными цифрами, например #6cbf4a; не пиши эту строку, если цвет выберет приложение>
        character: <имя>: <характер в одном-двух предложениях>
        character: <другое имя>: <другой характер>
        character: <третье имя>: <третий характер>
        pose: idle
        <32 строки ровно по 32 символа>
        pose: walk-0
        <32 строки>
        ... и так для каждой позы, в таком порядке: \(poses.joined(separator: ", "))

        Ключи name, kind, colour, character и pose, названия поз и символы ниже пиши ровно так, латиницей.
        Описание (kind) и характеры пиши по-русски; имена — латиницей.

        Символы, по одному на пиксель:
          .  ничего (прозрачно)
          o  контур, тёмная линия вокруг тела
          b  тело, основной цвет
          l  свет, блик вдоль верха и левой стороны внутри контура
          s  тень вдоль низа и правой стороны внутри контура
          k  пиксели глаз (чёрные). Каждый глаз — вертикальный блок из k; приложение моргает, опуская на него веко
          x  другие чёрные детали, которые не моргают (рот, пятнышко)

        Правила, которые проверяет приложение:
          - Каждая поза — ровно 32 строки ровно по 32 символа. Никаких других символов, никаких пробелов внутри строк.
          - Существо не выходит за столбцы с \(box.x + 1) по \(box.x + box.w) и строки с \(box.y + 1) по \(box.y + box.h) (считая с 1). Строки снаружи пустые.
          - Строка \(floor) — это пол: в каждой позе на строке \(floor) есть закрашенные пиксели. Существо стоит на ней и смотрит ВПРАВО.
          - Держи тело примерно по центру этой рамки по горизонтали; в углах экрана приложение поворачивает его вокруг центра.
          - Позы: idle — стоит на месте. walk-0 … walk-3 — один цикл ходьбы (walk-1 чуть сплющена, walk-3 вытянута, ноги чередуются).
            jump — вытянуто вверх, ноги поджаты. land — очень сплющено и широко. sleep-0 и sleep-1 — осело вниз,
            глаза всё так же нарисованы k (приложение само их закроет), sleep-1 на одну строку ниже sleep-0.
          - Используй только . o b l s k x. Не добавляй цветов, комментариев и пояснений. Выведи текстовый блок и больше ничего.
          - Три персонажа — это те, кем станут существа этого вида, когда заговорят друг с другом: дай каждому
            свой голос, подходящий к тому, что это за существо.

        Вот поза idle встроенного существа — пример размера и стиля (квадратное тело, два глаза, маленькие ноги):

        pose: idle
        \(example.joined(separator: "\n"))
        """
    }
}
