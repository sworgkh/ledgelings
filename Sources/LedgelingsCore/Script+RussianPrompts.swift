extension Script {
    /// `agentPrompt` in Russian: the same format and rules, asking for Russian lines.
    /// Tags and placeholders stay English, the parser reads them.
    public static func russianAgentPrompt(cast: [Character], count: Int = 40) -> String {
        let who = cast.isEmpty ? "" : "\nСущества, которые могут разговаривать (реплика должна подходить любому из них, поэтому никогда не пиши имён; пиши {speaker} и {listener}):\n"
            + cast.map { "- \($0.name): \(Banter.spoken(CursorMood.current.persona($0.persona)))" }.joined(separator: "\n") + "\n"
        return """
        Напиши \(count) коротких разговоров (столько блоков) между двумя маленькими пиксельными существами, которые живут на краях экрана компьютера. \
        Они ползают по нижнему краю, по бокам и по потолку, \(CursorMood.current.agentPhrase), ночью спят, а иногда врезаются друг в друга. \
        Каждый разговор случается, когда одно существо врезается в другое. Пусть будет смешно, с подколками и немного странно, но никогда не зло.

        Пиши по-русски. Существа говорят друг другу «ты». Мы не знаем их пола, поэтому избегай прошедшего времени \
        и прилагательных с родом для говорящего и собеседника («я видел», «ты устала»): пиши в настоящем времени.

        Формат, строго:
        - Один разговор на блок, между блоками пустая строка.
        - Реплики в блоке чередуются: первая — того, кто врезался, вторая — того, в кого врезались, и так далее. От двух до четырёх реплик в блоке, чаще две.
        - В каждой реплике не больше 20 слов. Без имён в начале, без кавычек, без нумерации.
        - Подстановки (пиши их ровно так, латиницей): {speaker} — тот, кто говорит реплику, {listener} — другой, {flower} — цветок, который дарят, {holiday} — праздник, который сегодня.
        - {flower} и {holiday} подставляются в именительном падеже, так что ставь их туда, где он подходит: «Держи: {flower}.», «Сегодня {holiday}!».
        - *Звёздочками* выделяй действие или ударение, например *вздыхает*.
        - Примерно четверть блоков начинается со строки-тега [flower]: тот, кто врезался, только что подарил другому {flower}, и реплики об этом.
        - Несколько блоков начинаются с [night]: темно, и им полагается спать. У блока могут быть оба тега: [night, flower].
        - Несколько блоков начинаются с [holiday]: сегодня праздник, его название — {holiday} (это может быть Рождество, Ханука, Ураза-байрам или любой другой), поэтому реплики должны подходить к любому из них.
        - Блоки без строки-тега случаются в любое время.
        - Теги пиши ровно так, по-английски, в квадратных скобках.
        \(who)
        Пример:

        Уютный у тебя край, {listener}.
        Был уютный. До тебя.

        [flower]
        Держи. Нашлось под курсором: {flower}.
        Это... тикает?

        [night]
        *шёпотом* Ты не спишь?
        Сплю.

        Выведи только блоки, ничего до и после.
        """
    }
}
